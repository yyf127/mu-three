/**
 * 渲染画质档位（阶段 1：**只提清晰度，不碰光照**）。
 *
 * ## 边界
 *
 * MU 0.97 的美术是「预烘焙贴图 + 无光照管线」—— 角色贴图本身就画好了明暗，
 * 所以**不加光源、不换 PBR 材质**，原版风味才保得住。
 * 这里只做纯粹的**采样质量**提升：
 *
 *   - 各向异性过滤拉满      → 斜视角（地面、远处墙面）不再糊成一团
 *   - pixelRatio 上限提高    → 高分屏上边缘更锐利
 *
 * 光照明暗、色调映射一律不动 —— 那属于「改美术方向」，不是「提精度」。
 * 试过 ACES 色调映射与全屏锐化，都因为改变了原版观感（前者加电影调、
 * 后者把低模的圆柱锐成多边形柱）而回退，见 main.ts 的注释。
 */

/* ------------------------------------------------------------------ */
/* 各向异性过滤                                                        */
/* ------------------------------------------------------------------ */

/**
 * 当前设备支持的最大各向异性倍数（通常 16，个别 8 或 4）。
 *
 * three 的 `WebGLCapabilities.getMaxAnisotropy()` 依赖 `EXT_texture_filter_anisotropic`
 * 扩展；拿不到时它会退回 0，这时按 1 处理（等于关闭）。
 */
let maxAniso: number | null = null;

/** 由 `main.ts` 在创建 renderer 后注入（`texture.ts` 不该反向依赖渲染器） */
export function setMaxAnisotropy(v: number) {
  maxAniso = Number.isFinite(v) && v > 0 ? v : 1;
}

/**
 * 贴图该用的各向异性倍数。
 *
 * 原来两处都写死 4 —— 现代独显/核显普遍支持 16，写死 4 意味着
 * 斜着看地面时只采 4 个样本，纹理糊得很明显。
 *
 * 上限取设备最大值，但**不低于 8**（能跑 WebGL2 的设备基本都支持 16/8；
 * 万一拿到的是 4 或更小，就照实用它本来的值，别硬凑）。
 */
export function textureAnisotropy(): number {
  const cap = maxAniso ?? 4;
  return Math.max(1, Math.min(cap, 16));
}

