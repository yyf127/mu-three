/**
 * 像素比上限。
 *
 * 原值 2：在 DPR=3 的手机/4K 屏上其实只渲染了 2/3 的分辨率再拉大，边缘发虚。
 * 提到 3 后这类屏幕能满分辨率渲染。桌面 DPR=1/2 的机器不受影响（本来就 ≤ 上限）。
 *
 * 代价是像素量最多 ↑ 2.25 倍（3²/2²）—— 这是阶段 1 唯一明显的性能开销，
 * 所以仍然设上限（不直接 `setPixelRatio(devicePixelRatio)`，避免 4K 屏上
 * 像素量暴涨到不可控）。
 */
export const MAX_PIXEL_RATIO = 3;
